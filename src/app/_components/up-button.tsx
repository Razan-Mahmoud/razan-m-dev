"use client";

import { useEffect, useState } from "react";

export default function ScrollToTopButton() {
  const [isVisible, setIsVisible] = useState(false);

  useEffect(() => {
    const toggleVisibility = () => {
      if (window.scrollY > 300) {
        setIsVisible(true);
      } else {
        setIsVisible(false);
      }
    };

    window.addEventListener("scroll", toggleVisibility);

    return () => window.removeEventListener("scroll", toggleVisibility);
  }, []);

  const scrollToTop = () => {
    window.scrollTo({
      top: 0,
      behavior: "smooth",
    });
  };

  if (!isVisible) return null;

  return (
    <button
      onClick={scrollToTop}
      className="aria-label='Scroll to top' fixed right-2 bottom-2 z-50 rounded-full bg-sky-300 p-3 text-sky-800 shadow-lg transition duration-300 ease-in-out hover:bg-sky-400 md:right-4 md:bottom-4 dark:bg-blue-900 dark:text-slate-300 dark:hover:bg-blue-800"
    >
      {/* Up Arrow SVG Icon */}
      <svg
        xmlns="http://w3.org"
        className="h-6 w-6"
        fill="none"
        viewBox="0 0 24 24"
        stroke="currentColor"
        strokeWidth={3}
      >
        <path strokeLinecap="round" strokeLinejoin="round" d="M5 10l7-7m0 0l7 7m-7-7v18" />
      </svg>
    </button>
  );
}
